"""Title-block recognition: attribute tags and label/value text pairs, with honest 'inferred' and 'confidence'.  Pure, no engine."""

import pytest

from eng_toolkit.domains.drawing import titleblock as T

Text = T.TextRec
Block = T.AttribBlock


# --------------------------------------------------------------------------- vocabulary


@pytest.mark.parametrize(
    ("label", "field"),
    [
        ("TITLE", "title"),
        ("Part No.", "part_number"),
        ("PART_NUMBER", "part_number"),
        ("DWG-NO", "part_number"),
        ("Drawing No:", "part_number"),
        ("REV", "revision"),
        ("MATERIAL", "material"),
        ("SCALE", "scale"),
        ("SHEET", "sheet"),
        ("DRAWN BY", "drawn_by"),
        ("PROJECTION", "projection"),
        ("GENERAL TOLERANCE", "general_tolerance"),
        ("圖號", "part_number"),
        ("料號：", "part_number"),
        ("品名", "title"),
        ("材質", "material"),
        ("版次", "revision"),
        ("比例", "scale"),
        ("日期", "date"),
        ("審核", "checked_by"),
        ("一般公差", "general_tolerance"),
    ],
)
def test_known_labels_and_tags_map_to_a_field(label, field):
    assert T.canonical_field(label) == field


@pytest.mark.parametrize("text", ["BRACKET", "100", "NOTE 1", "", "UNREVIEWED - generated by eng-toolkit", "SECTION A-A"])
def test_other_text_is_not_a_label(text):
    assert T.canonical_field(text) is None


# --------------------------------------------------------------------------- attributes


def test_attribute_tags_are_exact_matches_not_guesses():
    blocks = [Block("TITLEBLOCK", "0", [("TITLE", "FLANGE"), ("DWG_NO", "FL-001"), ("REV", "B"), ("MATERIAL", "SS304"), ("ZONE", "x")])]
    found = T.from_attributes(blocks)
    assert found.block == "TITLEBLOCK"
    assert found.fields["title"] == T.Field("FLANGE", "attribute TITLE of block TITLEBLOCK", False, 1.0)
    assert found.fields["part_number"].value == "FL-001" and found.fields["part_number"].inferred is False
    assert found.fields["revision"].value == "B"
    assert found.unmatched == [("ZONE", "x")]


def test_chinese_tags_work():
    found = T.from_attributes([Block("圖框", "0", [("圖號", "A-100"), ("品名", "法蘭"), ("材質", "S45C")])])
    assert (found.fields["part_number"].value, found.fields["title"].value, found.fields["material"].value) == ("A-100", "法蘭", "S45C")


def test_the_block_with_the_most_recognised_tags_is_the_title_block():
    blocks = [
        Block("BALLOON", "0", [("NO", "7")]),
        Block("TB", "0", [("TITLE", "A"), ("SCALE", "1:2"), ("REV", "A")]),
        Block("PARTSLIST", "0", [("TITLE", "ignore me")]),
    ]
    found = T.from_attributes(blocks)
    assert found.block == "TB" and found.fields["title"].value == "A"


def test_a_block_with_a_single_recognised_tag_and_no_title_block_name_is_not_a_title_block():
    found = T.from_attributes([Block("BALLOON", "0", [("TITLE", "x")])])
    assert found.block is None and found.fields == {}


def test_empty_attribute_values_are_not_fields():
    found = T.from_attributes([Block("TB", "0", [("TITLE", "  "), ("REV", "A"), ("SCALE", "1:1")])])
    assert "title" not in found.fields and found.fields["revision"].value == "A"


# --------------------------------------------------------------------------- label pairs (the layout drawing_make_views writes)


def sheet_block(**values):
    """Label and value as slice 4 places them: label at the top of its cell, value near the bottom of the cell, left aligned."""
    x0, top = 100.0, 50.0
    bands = [
        (14.0, [("TITLE", "title", 0.0), ("PART NO.", "part_number", 120.0)]),
        (10.0, [("MATERIAL", "material", 0.0), ("REV.", "revision", 60.0), ("SCALE", "scale", 80.0), ("SHEET", "sheet", 110.0), ("PROJECTION", "projection", 140.0)]),
        (10.0, [("GENERAL TOLERANCE", "general_tolerance", 0.0)]),
    ]
    texts = []
    for height, cells in bands:
        bottom = top - height
        for label, key, offset in cells:
            texts.append(Text(label, x0 + offset + 1.5, top - 2.6, 1.8, "TITLE"))
            if values.get(key):
                texts.append(Text(values[key], x0 + offset + 1.5, bottom + 1.5, 5.0 if key == "title" else 3.5, "TITLE"))
        top = bottom
    texts.append(Text("UNREVIEWED - generated by eng-toolkit, not engineering approved", 101.5, 6.0, 3.0, "TITLE"))
    return texts


def test_values_below_their_labels_are_paired_and_marked_inferred():
    texts = sheet_block(title="BRACKET", part_number="BR-01", material="AL6061", revision="A", scale="1:2", sheet="A4", projection="THIRD ANGLE", general_tolerance="ISO 2768-m")
    found = T.from_label_pairs(texts)
    got = {k: f.value for k, f in found.fields.items()}
    assert got == {
        "title": "BRACKET",
        "part_number": "BR-01",
        "material": "AL6061",
        "revision": "A",
        "scale": "1:2",
        "sheet": "A4",
        "projection": "THIRD ANGLE",
        "general_tolerance": "ISO 2768-m",
    }
    assert all(f.inferred is True and 0.5 <= f.confidence < 1.0 for f in found.fields.values())
    assert all(f.source.startswith("label ") for f in found.fields.values())


def test_the_status_line_is_reported_as_status_not_taken_for_a_value():
    found = T.from_label_pairs(sheet_block(title="X"))
    assert found.fields["title"].value == "X"
    assert "general_tolerance" not in found.fields  # the cell is empty; the status line below it is not its value
    assert found.status.startswith("UNREVIEWED")


def test_an_empty_cell_does_not_take_the_value_of_the_cell_below_it():
    found = T.from_label_pairs(sheet_block(title="X", general_tolerance="ISO 2768-m"))  # no material, no part number
    assert "material" not in found.fields
    assert found.fields["general_tolerance"].value == "ISO 2768-m"
    assert "part_number" not in found.fields


def test_a_label_without_a_value_is_listed_as_empty():
    found = T.from_label_pairs(sheet_block(title="X"))
    assert "MATERIAL" in found.empty_labels


def test_label_and_value_in_one_string_with_a_colon():
    found = T.from_label_pairs([Text("DWG NO: FL-001", 0, 0, 2.5, "0"), Text("材質：S45C", 0, 10, 2.5, "0")])
    assert found.fields["part_number"].value == "FL-001"
    assert found.fields["material"].value == "S45C"
    assert found.fields["part_number"].inferred is True


def test_a_value_to_the_right_of_its_label_on_the_same_line():
    found = T.from_label_pairs([Text("PART NO.", 0, 0, 2.5, "TB"), Text("FL-001", 30, 0.2, 2.5, "TB")])
    assert found.fields["part_number"].value == "FL-001"


def test_a_value_on_another_layer_has_lower_confidence_than_one_on_the_same_layer():
    same = T.from_label_pairs([Text("SCALE", 0, 10, 2.5, "TB"), Text("1:2", 0, 5, 2.5, "TB")]).fields["scale"]
    other = T.from_label_pairs([Text("SCALE", 0, 10, 2.5, "TB"), Text("1:2", 0, 5, 2.5, "VALUES")]).fields["scale"]
    assert other.confidence < same.confidence


def test_text_far_from_any_label_is_not_a_value():
    found = T.from_label_pairs([Text("SCALE", 0, 10, 2.5, "TB"), Text("1:2", 0, -500, 2.5, "TB")])
    assert found.fields == {}


def test_each_value_is_used_once_by_the_closest_label():
    texts = [Text("REV", 0, 20, 2.5, "TB"), Text("MATERIAL", 0, 10, 2.5, "TB"), Text("AL6061", 0, 5, 2.5, "TB")]
    found = T.from_label_pairs(texts)
    assert found.fields["material"].value == "AL6061" and "revision" not in found.fields


# --------------------------------------------------------------------------- both


def test_attributes_win_and_a_conflicting_label_pair_is_reported():
    blocks = [Block("TB", "0", [("TITLE", "FROM ATTRIB"), ("REV", "A"), ("SCALE", "1:1")])]
    texts = [Text("TITLE", 0, 10, 2.5, "T"), Text("FROM TEXT", 0, 5, 2.5, "T"), Text("MATERIAL", 30, 10, 2.5, "T"), Text("AL", 30, 5, 2.5, "T")]
    block = T.build(blocks, texts)
    assert block.method == "attributes+label_pairs"
    assert block.fields["title"].value == "FROM ATTRIB" and block.fields["title"].inferred is False
    assert block.fields["material"].value == "AL" and block.fields["material"].inferred is True
    assert block.conflicts == [{"field": "title", "attribute": "FROM ATTRIB", "text": "FROM TEXT"}]


def test_nothing_found_is_said_plainly():
    block = T.build([], [Text("NOTE", 0, 0, 2.5, "0")])
    assert block.method == "none" and block.fields == {}
