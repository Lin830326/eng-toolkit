"""What a drawing made by this toolkit looks like: layers, linetypes, dimension style, sheet frame and title block.

Pure data, no engine.  The DXF writer (``dxf.py``) draws from it and the future reader recognises a drawing of ours
by it, so the two cannot drift apart.  Lengths are millimetres on the sheet; line weights are millimetres.
"""

from __future__ import annotations

from dataclasses import dataclass

# --------------------------------------------------------------------------- layers


@dataclass(frozen=True)
class LayerSpec:
    name: str
    weight_mm: float  # DXF lineweight in 1/100 mm; one of the standard values
    linetype: str = "CONTINUOUS"


FRAME = LayerSpec("FRAME", 0.7)
TITLE = LayerSpec("TITLE", 0.35)
OUTLINE = LayerSpec("OUTLINE", 0.5)  # visible edges
HIDDEN = LayerSpec("HIDDEN", 0.25, "HIDDEN_MM")
CENTER = LayerSpec("CENTER", 0.25, "CENTER_MM")
DIM = LayerSpec("DIM", 0.25)
TEXT = LayerSpec("TEXT", 0.25)
LAYERS: tuple[LayerSpec, ...] = (FRAME, TITLE, OUTLINE, HIDDEN, CENTER, DIM, TEXT)
LAYER_BY_NAME: dict[str, LayerSpec] = {layer.name: layer for layer in LAYERS}

# --------------------------------------------------------------------------- linetypes

# DXF pattern: total length, then dash (+) and gap (-) lengths.  The linetypes that ship with CAD programs are
# inch based and render solid at millimetre scale, so these are ours.
LINETYPES: dict[str, tuple[float, ...]] = {
    "HIDDEN_MM": (5.0, 3.0, -2.0),
    "CENTER_MM": (28.0, 20.0, -3.0, 2.0, -3.0),
}


def dash_array_mm(linetype: str) -> tuple[float, ...]:
    """The on/off lengths of a linetype in mm for a PDF dash array; empty for a continuous line."""
    pattern = LINETYPES.get(linetype)
    return () if pattern is None else tuple(abs(v) for v in pattern[1:])


